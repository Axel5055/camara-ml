    public function run(): void
    {
        $this->call(CategorySeeder::class);

        $categories = Category::query()->pluck('id', 'name');

        foreach (self::PRODUCTS as [$name, $code, $category, $previousCode]) {
            $product = Product::query()->where('code', $code)->first()
                ?? Product::query()->where('code', $previousCode)->first();

            if ($product === null) {
                Product::query()->create([
                    'name' => $name,
                    'code' => $code,
                    'category_id' => $categories[$category],
                    'description' => 'Código anterior: '.$previousCode,
                    'is_active' => true,
                ]);

                continue;
            }

            if ($product->code !== $code && ! $product->boxes()->exists()) {
                $product->update(['code' => $code, 'description' => $product->description ?: 'Código anterior: '.$previousCode]);
            }
        }
    }
